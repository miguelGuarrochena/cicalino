/* Se exporta para el test de paridad: que una clave agregada en un idioma y
 * olvidada en el otro no llegue a producción como texto en castellano
 * apareciendo en el panel en inglés. */
export const DICT = dict;

export const translate = (
  locale: Locale,
  key: string,
  vars?: Record<string, string | number>,
): string => {
  const parts = key.split(".");
  let node: unknown = dict[locale];
  for (const p of parts) {
    if (p === "__proto__" || p === "constructor" || p === "prototype")
      return key;
    if (
      node &&
      typeof node === "object" &&
      Object.prototype.hasOwnProperty.call(node, p)
    ) {
      node = (node as Record<string, unknown>)[p];
    } else {
      return key;
    }
  }
  let out = typeof node === "string" ? node : key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      out = out.replace(`{${k}}`, String(v));
    }
  }
  return out;
};
